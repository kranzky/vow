use crate::ast::*;
use crate::check::{CallKind, Info, Ty};
use crate::pretty;

pub struct Gen<'a> {
    info: &'a Info,
    files: &'a [String],
    out: Vec<String>,
    ind: usize,
    tmp: usize,
    strs: Vec<Vec<u8>>,
    inout: Vec<String>,
}

fn c_string(bytes: &[u8]) -> String {
    let mut s = String::from("\"");
    for &b in bytes {
        match b {
            b'"' => s.push_str("\\\""),
            b'\\' => s.push_str("\\\\"),
            b'?' => s.push_str("\\?"),
            0x20..=0x7e => s.push(b as char),
            _ => s.push_str(&format!("\\{:03o}", b)),
        }
    }
    s.push('"');
    s
}

pub fn generate(items: &[Item], info: &Info, files: &[String], verified: bool) -> String {
    let mut g = Gen { info, files, out: Vec::new(), ind: 0, tmp: 0, strs: Vec::new(), inout: Vec::new() };
    let mut body = Vec::new();
    for it in items {
        if let Item::Fn(f) = it {
            g.out.clear();
            g.tmp = 0;
            g.function(f);
            body.extend(g.out.drain(..));
        }
    }
    let mut c = Vec::new();
    c.push("// Generated by vowc. Do not edit.".to_string());
    if verified {
        c.push("#define VOW_VERIFIED 1".to_string());
    }
    c.push("#include \"vow_rt.h\"".to_string());
    c.push(String::new());
    c.push(format!("static V vow_s[{}];", g.strs.len().max(1)));
    for it in items {
        if let Item::Fn(f) = it {
            c.push(format!("static V f_{}({});", f.name, params(f)));
        }
    }
    c.push(String::new());
    c.extend(body);
    c.push("int main(int argc, char **argv) {".to_string());
    c.push("    vow_argc = argc;".to_string());
    c.push("    vow_argv = argv;".to_string());
    for (i, s) in g.strs.iter().enumerate() {
        c.push(format!("    vow_s[{}] = vstr_new({}, {});", i, c_string(s), s.len()));
    }
    c.push("    f_main();".to_string());
    c.push("    fflush(stdout);".to_string());
    c.push("    return 0;".to_string());
    c.push("}".to_string());
    c.join("\n") + "\n"
}

fn params(f: &FnDecl) -> String {
    if f.params.is_empty() {
        return "void".into();
    }
    let ps: Vec<String> =
        f.params.iter().map(|p| format!("{} l_{}", if p.inout { "V *" } else { "V" }, p.name)).collect();
    ps.join(", ")
}

impl<'a> Gen<'a> {
    fn line(&mut self, s: String) {
        self.out.push(format!("{}{}", "    ".repeat(self.ind), s));
    }

    fn fresh(&mut self) -> String {
        self.tmp += 1;
        format!("t{}", self.tmp)
    }

    fn bind(&mut self, rhs: String) -> String {
        let t = self.fresh();
        self.line(format!("V {} = {};", t, rhs));
        t
    }

    fn str_lit(&mut self, s: &str) -> String {
        let b = s.as_bytes().to_vec();
        let i = match self.strs.iter().position(|x| *x == b) {
            Some(i) => i,
            None => {
                self.strs.push(b);
                self.strs.len() - 1
            }
        };
        format!("vow_s[{}]", i)
    }

    fn loc(&self, pos: crate::diag::Pos) -> String {
        let f = self.files.get(pos.file as usize).map(|s| s.as_str()).unwrap_or("?");
        format!("{}:{}", f, pos.line)
    }

    fn var(&self, n: &str) -> String {
        if self.inout.iter().any(|x| x == n) {
            format!("(*l_{})", n)
        } else {
            format!("l_{}", n)
        }
    }

    fn function(&mut self, f: &FnDecl) {
        self.inout = f.params.iter().filter(|p| p.inout).map(|p| p.name.clone()).collect();
        self.line(format!("static V f_{}({}) {{", f.name, params(f)));
        self.ind += 1;
        self.block(&f.body);
        self.line("return 0;".into());
        self.ind -= 1;
        self.line("}".into());
        self.line(String::new());
    }

    fn block(&mut self, stmts: &[Stmt]) {
        for s in stmts {
            self.stmt(s);
        }
    }

    fn braced(&mut self, stmts: &[Stmt]) {
        self.ind += 1;
        self.block(stmts);
        self.ind -= 1;
    }

    fn stmt(&mut self, s: &Stmt) {
        match &s.kind {
            SK::Let { name, value, .. } => {
                let v = self.expr(value);
                if name == "_" {
                    self.line(format!("(void){};", v));
                } else {
                    self.line(format!("V l_{} = {};", name, v));
                }
            }
            SK::Set { name, value } => {
                let v = self.expr(value);
                let lv = self.var(name);
                self.line(format!("{} = {};", lv, v));
            }
            SK::Return(None) => self.line("return 0;".into()),
            SK::Return(Some(e)) => {
                let v = self.expr(e);
                self.line(format!("return {};", v));
            }
            SK::If { arms, els } => self.if_chain(arms, els),
            SK::While { cond, body, .. } => {
                self.line("for (;;) {".into());
                self.ind += 1;
                let c = self.expr(cond);
                self.line(format!("if (!{}) break;", c));
                self.block(body);
                self.ind -= 1;
                self.line("}".into());
            }
            SK::ForRange { var, lo, hi, body, .. } => {
                let a = self.expr(lo);
                let b = self.expr(hi);
                self.line(format!("for (V l_{v} = {a}; VI(l_{v}) < VI({b}); l_{v} = (V)(VI(l_{v}) + 1)) {{", v = var, a = a, b = b));
                self.braced(body);
                self.line("}".into());
            }
            SK::ForEach { var, list, body, .. } => {
                let l = self.expr(list);
                let k = self.fresh();
                self.line(format!("for (int64_t {k} = 0; {k} < VL({l})->len; {k}++) {{", k = k, l = l));
                self.ind += 1;
                self.line(format!("V l_{} = VL({})->buf->items[{}];", var, l, k));
                self.block(body);
                self.ind -= 1;
                self.line("}".into());
            }
            SK::Match { scrut, cases, els } => self.match_stmt(scrut, cases, els),
            SK::Assert(e) => {
                self.line("#ifndef VOW_VERIFIED".into());
                let c = self.expr(e);
                let msg = format!("assertion failed at {}: {}", self.loc(s.pos), pretty::expr(e));
                self.line(format!("if (!{}) vow_panic({});", c, c_string(msg.as_bytes())));
                self.line("#endif".into());
            }
            SK::Check(e) => {
                let c = self.expr(e);
                let msg = format!("check failed at {}: {}", self.loc(s.pos), pretty::expr(e));
                self.line(format!("if (!{}) vow_panic({});", c, c_string(msg.as_bytes())));
            }
            SK::Break => self.line("break;".into()),
            SK::Continue => self.line("continue;".into()),
            SK::Expr(e) => {
                let v = self.expr(e);
                self.line(format!("(void){};", v));
            }
        }
    }

    fn if_chain(&mut self, arms: &[(Expr, Vec<Stmt>)], els: &Option<Vec<Stmt>>) {
        let (c, body) = &arms[0];
        let cv = self.expr(c);
        self.line(format!("if ({}) {{", cv));
        self.braced(body);
        if arms.len() > 1 {
            self.line("} else {".into());
            self.ind += 1;
            self.if_chain(&arms[1..], els);
            self.ind -= 1;
            self.line("}".into());
        } else if let Some(b) = els {
            self.line("} else {".into());
            self.braced(b);
            self.line("}".into());
        } else {
            self.line("}".into());
        }
    }

    fn match_stmt(&mut self, scrut: &Expr, cases: &[Case], els: &Option<Vec<Stmt>>) {
        let st = self.info.ty(scrut);
        let v = self.expr(scrut);
        let variants = self.info.variants(&st);
        let tag = if variants.is_some() { self.bind(format!("VP({})[0]", v)) } else { v.clone() };
        let mut first = true;
        for c in cases {
            let cond = match &c.pat {
                Pat::Int(n) => format!("VI({}) == INT64_C({})", tag, n),
                Pat::Str(s) => {
                    let l = self.str_lit(s);
                    format!("vstr_eq({}, {})", tag, l)
                }
                Pat::Variant { name, .. } => {
                    let vi = variants.as_ref().unwrap().iter().position(|x| x.name == *name).unwrap();
                    format!("{} == {}", tag, vi)
                }
            };
            let kw = if first { "if" } else { "} else if" };
            first = false;
            self.line(format!("{} ({}) {{", kw, cond));
            self.ind += 1;
            if let Pat::Variant { name, binds } = &c.pat {
                let vs = variants.as_ref().unwrap();
                let vinfo = vs.iter().find(|x| x.name == *name).unwrap();
                for (f, b) in binds {
                    let fi = vinfo.fields.iter().position(|(n, _)| n == f).unwrap();
                    self.line(format!("V l_{} = VP({})[{}];", b, v, fi + 1));
                }
            }
            self.block(&c.body);
            self.ind -= 1;
        }
        match els {
            Some(b) => {
                if first {
                    self.line("{".into());
                } else {
                    self.line("} else {".into());
                }
                self.braced(b);
                self.line("}".into());
            }
            None => {
                if !first {
                    self.line("} else {".into());
                    self.line("    vow_panic(\"unreachable: corrupt enum tag\");".into());
                    self.line("}".into());
                }
            }
        }
    }

    fn is_str_map(&self, e: &Expr) -> i32 {
        match self.info.ty(e) {
            Ty::Map(k, _) => (*k == Ty::Str) as i32,
            _ => 0,
        }
    }

    pub fn expr(&mut self, e: &Expr) -> String {
        match &e.kind {
            EK::Int(n) => format!("(V)INT64_C({})", n),
            EK::Str(s) => self.str_lit(s),
            EK::Bool(b) => (if *b { "1" } else { "0" }).to_string(),
            // Copied so that a later inout argument in the same call cannot change it.
            EK::Var(n) => {
                let v = self.var(n);
                self.bind(v)
            }
            EK::It | EK::Result | EK::Hole(_) => "0 /* spec-only */".into(),
            EK::Call(_, args) => self.call(e, args),
            EK::List(items) => {
                let mut acc = self.bind("vlist_empty()".into());
                for it in items {
                    let v = self.expr(it);
                    self.line(format!("{} = vlist_push({}, {});", acc, acc, v));
                }
                acc = acc.clone();
                acc
            }
            EK::EmptyMap => "vmap_empty()".into(),
            EK::Index(o, i) => {
                let ov = self.expr(o);
                let iv = self.expr(i);
                match self.info.ty(o) {
                    Ty::Str => self.bind(format!("vstr_byte({}, {})", ov, iv)),
                    _ => self.bind(format!("vlist_get({}, {})", ov, iv)),
                }
            }
            EK::Field(o, f) => {
                if let Some(ci) = self.info.calls.get(&e.id) {
                    if let CallKind::Variant(_, vi) = ci.kind {
                        return self.bind(format!("vow_variant0({})", vi));
                    }
                }
                let ov = self.expr(o);
                let sn = match self.info.ty(o) {
                    Ty::Struct(n) => n,
                    _ => unreachable!(),
                };
                let fi = self.info.structs[&sn].iter().position(|(n, _)| n == f).unwrap();
                self.bind(format!("VP({})[{}]", ov, fi))
            }
            EK::With(o, args) => {
                let ov = self.expr(o);
                let sn = match self.info.ty(o) {
                    Ty::Struct(n) => n,
                    _ => unreachable!(),
                };
                let fields = self.info.structs[&sn].clone();
                let mut vals = Vec::new();
                for a in args {
                    let v = self.expr(&a.value);
                    vals.push((a.name.clone().unwrap(), v));
                }
                let r = self.bind(format!("vow_copy({}, {})", ov, fields.len()));
                for (n, v) in vals {
                    let fi = fields.iter().position(|(f, _)| *f == n).unwrap();
                    self.line(format!("VP({})[{}] = {};", r, fi, v));
                }
                r
            }
            EK::Unary(op, x) => {
                let v = self.expr(x);
                if op == "-" {
                    self.bind(format!("vneg({})", v))
                } else {
                    self.bind(format!("(V)!{}", v))
                }
            }
            EK::Binary(op, l, r) => self.binary(op, l, r),
            EK::Quant(q, v, lo, hi, body) => {
                let a = self.expr(lo);
                let b = self.expr(hi);
                let forall = q == "forall";
                let t = self.bind(if forall { "1".into() } else { "0".into() });
                self.line(format!("for (V l_{v} = {a}; VI(l_{v}) < VI({b}); l_{v} = (V)(VI(l_{v}) + 1)) {{", v = v, a = a, b = b));
                self.ind += 1;
                let bv = self.expr(body);
                if forall {
                    self.line(format!("if (!{}) {{ {} = 0; break; }}", bv, t));
                } else {
                    self.line(format!("if ({}) {{ {} = 1; break; }}", bv, t));
                }
                self.ind -= 1;
                self.line("}".into());
                t
            }
        }
    }

    fn binary(&mut self, op: &str, l: &Expr, r: &Expr) -> String {
        match op {
            "and" | "or" | "implies" => {
                let a = self.expr(l);
                let t = self.bind(if op == "implies" { "1".into() } else { a.clone() });
                let guard = if op == "or" { format!("!{}", t) } else { a };
                self.line(format!("if ({}) {{", guard));
                self.ind += 1;
                let b = self.expr(r);
                self.line(format!("{} = {};", t, b));
                self.ind -= 1;
                self.line("}".into());
                t
            }
            _ => {
                let a = self.expr(l);
                let b = self.expr(r);
                let lt = self.info.ty(l);
                let rhs = match op {
                    "+" => format!("vadd({}, {})", a, b),
                    "-" => format!("vsub({}, {})", a, b),
                    "*" => format!("vmul({}, {})", a, b),
                    "/" => format!("vdiv({}, {})", a, b),
                    "%" => format!("vmod({}, {})", a, b),
                    "<" | "<=" | ">" | ">=" => format!("(V)(VI({}) {} VI({}))", a, op, b),
                    "==" | "!=" => {
                        let eq = if lt == Ty::Str { format!("vstr_eq({}, {})", a, b) } else { format!("(V)({} == {})", a, b) };
                        if op == "==" {
                            eq
                        } else {
                            format!("(V)!{}", eq)
                        }
                    }
                    "++" => {
                        if lt == Ty::Str {
                            format!("vstr_cat({}, {})", a, b)
                        } else {
                            format!("vlist_cat({}, {})", a, b)
                        }
                    }
                    _ => unreachable!(),
                };
                self.bind(rhs)
            }
        }
    }

    fn call(&mut self, e: &Expr, args: &[Arg]) -> String {
        let ci = self.info.calls[&e.id].clone();
        // Evaluate arguments in written order, then pass them in parameter order.
        let mut vals: Vec<String> = Vec::new();
        for a in args {
            let v = match (&a.value.kind, a.inout) {
                (EK::Var(n), true) => {
                    if self.inout.iter().any(|x| x == n) {
                        format!("l_{}", n)
                    } else {
                        format!("&l_{}", n)
                    }
                }
                _ => self.expr(&a.value),
            };
            vals.push(v);
        }
        let p: Vec<String> = ci.order.iter().map(|i| vals[*i].clone()).collect();
        let pa: Vec<&Expr> = ci.order.iter().map(|i| &args[*i].value).collect();
        match &ci.kind {
            CallKind::User(n) => self.bind(format!("f_{}({})", n, p.join(", "))),
            CallKind::Struct(_) => {
                let r = self.bind(format!("vow_new({})", p.len()));
                for (i, v) in p.iter().enumerate() {
                    self.line(format!("VP({})[{}] = {};", r, i, v));
                }
                r
            }
            CallKind::Variant(_, vi) => {
                let r = self.bind(format!("vow_new({})", p.len() + 1));
                self.line(format!("VP({})[0] = {};", r, vi));
                for (i, v) in p.iter().enumerate() {
                    self.line(format!("VP({})[{}] = {};", r, i + 1, v));
                }
                r
            }
            CallKind::Builtin(n) => {
                let rhs = match n.as_str() {
                    "len" => match self.info.ty(pa[0]) {
                        Ty::Str => format!("vstr_len({})", p[0]),
                        Ty::Map(..) => format!("vmap_len({})", p[0]),
                        _ => format!("vlist_len({})", p[0]),
                    },
                    "push" => format!("vlist_push({}, {})", p[0], p[1]),
                    "set_at" => format!("vlist_set_at({}, {}, {})", p[0], p[1], p[2]),
                    "slice" => match self.info.ty(pa[0]) {
                        Ty::Str => format!("vstr_slice({}, {}, {})", p[0], p[1], p[2]),
                        _ => format!("vlist_slice({}, {}, {})", p[0], p[1], p[2]),
                    },
                    "join" => format!("vjoin({}, {})", p[0], p[1]),
                    "int_to_str" => format!("vint_to_str({})", p[0]),
                    "str_to_int" => format!("vstr_to_int({})", p[0]),
                    "char" => format!("vchar({})", p[0]),
                    "hash" => format!("vhash({})", p[0]),
                    "insert" => format!("vmap_insert({}, {}, {}, {})", p[0], p[1], p[2], self.is_str_map(pa[0])),
                    "lookup" => format!("vmap_lookup({}, {}, {})", p[0], p[1], self.is_str_map(pa[0])),
                    "has" => format!("vmap_has({}, {}, {})", p[0], p[1], self.is_str_map(pa[0])),
                    "keys" => format!("vmap_keys({})", p[0]),
                    "panic" => {
                        self.line(format!("vow_panic(VS({})->data);", p[0]));
                        return "0".into();
                    }
                    "exit" => {
                        self.line(format!("vexit({});", p[0]));
                        return "0".into();
                    }
                    "print" => format!("vprint({})", p[0]),
                    "eprint" => format!("veprint({})", p[0]),
                    "read_file" => format!("vread_file({})", p[0]),
                    "write_file" => format!("vwrite_file({}, {})", p[0], p[1]),
                    "args" => "vargs()".into(),
                    "make_dir" => format!("vmake_dir({})", p[0]),
                    "list_dir" => format!("vlist_dir({})", p[0]),
                    "getenv" => format!("vgetenv({})", p[0]),
                    "run" => format!("vrun({}, {})", p[0], p[1]),
                    "is_some" => format!("(V)(VP({})[0] == 1)", p[0]),
                    "is_none" => format!("(V)(VP({})[0] == 0)", p[0]),
                    "value_or" => format!("(VP({o})[0] == 1 ? VP({o})[1] : {d})", o = p[0], d = p[1]),
                    _ => unreachable!(),
                };
                self.bind(rhs)
            }
        }
    }
}
