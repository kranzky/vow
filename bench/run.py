#!/usr/bin/env python3
"""Builds and times the benchmarks in every language; writes RESULTS.md.

Each program is the same straightforward, single-threaded algorithm. Every output is
checked against C's before it is timed. Time is the best of three runs (wall clock);
memory is the peak memory footprint of that run, from /usr/bin/time -l (macOS)."""
import hashlib, os, platform, subprocess, sys, time

ROOT = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(ROOT)
BUILD = os.path.join(ROOT, "build")
RUNS = 3

BENCHMARKS = [
    ("binarytrees", ["18"], "allocation and recursion"),
    ("fannkuch", ["10"], "integer arrays and permutations"),
    ("knucleotide", [os.path.join(BUILD, "knucleotide-input.fa")], "strings and hash maps"),
]
LANGS = ["Vow", "C", "Rust", "Go", "JavaScript", "Python"]

def sh(cmd, **kw):
    subprocess.run(cmd, check=True, **kw)

def build(name):
    src = os.path.join(ROOT, name, name)
    out = os.path.join(BUILD, name)
    sh([os.path.join(REPO, "build", "vowc"), "build", src + ".vow", "-o", out + "-vow", "--no-cache"])
    sh(["clang", "-O2", "-o", out + "-c", src + ".c"])
    sh(["rustc", "-O", "-o", out + "-rust", src + ".rs"])
    sh(["go", "build", "-o", out + "-go", src + ".go"])
    return {
        "Vow": [out + "-vow"], "C": [out + "-c"], "Rust": [out + "-rust"], "Go": [out + "-go"],
        "JavaScript": ["node", src + ".js"], "Python": ["python3", src + ".py"],
    }

def measure(cmd):
    t0 = time.time()
    p = subprocess.run(["/usr/bin/time", "-l"] + cmd, capture_output=True, timeout=1800)
    wall = time.time() - t0
    if p.returncode != 0:
        raise RuntimeError(f"{cmd} failed: {p.stderr.decode()[-300:]}")
    # Peak memory footprint counts compressed pages too; resident set size does not,
    # and macOS compresses memory heavily under pressure.
    rss = next(int(l.split()[0]) for l in p.stderr.decode().splitlines() if "peak memory footprint" in l)
    return wall, rss, hashlib.md5(p.stdout).hexdigest()

def version(cmd):
    return subprocess.run(cmd, capture_output=True, text=True).stdout.strip().splitlines()[0]

def main():
    os.makedirs(BUILD, exist_ok=True)
    sh(["clang", "-O2", "-o", os.path.join(BUILD, "fasta"), os.path.join(ROOT, "fasta.c")])
    with open(os.path.join(BUILD, "knucleotide-input.fa"), "wb") as f:
        sh([os.path.join(BUILD, "fasta"), "100000"], stdout=f)
    results = {}
    for name, args, _ in BENCHMARKS:
        cmds = build(name)
        expected = None
        for lang in ["C"] + [l for l in LANGS if l != "C"]:
            best = None
            for _ in range(RUNS):
                wall, rss, digest = measure(cmds[lang] + args)
                if expected is None:
                    expected = digest
                if digest != expected:
                    sys.exit(f"{name}/{lang}: output differs from C")
                if best is None or wall < best[0]:
                    best = (wall, rss)
            results[(name, lang)] = best
            print(f"{name:12} {lang:10} {best[0]:8.3f}s {best[1] / 2**20:8.0f} MB", flush=True)
    write_results(results)

def write_results(results):
    lines = ["# Benchmark results", "",
             f"Machine: {platform.machine()} {subprocess.run(['sysctl', '-n', 'machdep.cpu.brand_string'], capture_output=True, text=True).stdout.strip()}, "
             f"{int(subprocess.run(['sysctl', '-n', 'hw.memsize'], capture_output=True, text=True).stdout) // 2**30} GB, macOS {platform.mac_ver()[0]}.", "",
             "Toolchains: " + "; ".join([version(["clang", "--version"]), version(["rustc", "--version"]),
                                         version(["go", "version"]), "Node " + version(["node", "--version"]),
                                         version(["python3", "--version"]), "Vow: seed compiler, C via clang -O2"]) + ".", "",
             f"Best of {RUNS} wall-clock runs; memory is the peak memory footprint (including compressed pages). Generated by `bench/run.py`.", ""]
    for name, args, what in BENCHMARKS:
        c_time = results[(name, "C")][0]
        arg = os.path.basename(args[0]) if "/" in args[0] else args[0]
        lines += [f"## {name} ({what}, input {arg})", "", "| Language | Time | Relative to C | Memory |", "|---|---|---|---|"]
        for lang in LANGS:
            t, rss = results[(name, lang)]
            lines.append(f"| {lang} | {t:.2f} s | {t / c_time:.1f}x | {rss / 2**20:.0f} MB |")
        lines.append("")
    with open(os.path.join(ROOT, "RESULTS.md"), "w") as f:
        f.write("\n".join(lines))

main()
